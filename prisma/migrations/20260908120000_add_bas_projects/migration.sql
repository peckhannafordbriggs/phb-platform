-- =============================================================================
-- SECTION 4 - bas_sites.org_id and bas_projects.org_id must agree
--
-- bas_sites now has both org_id and project_id, and bas_projects has org_id, so
-- the same fact is written in two places and nothing declarative stops them
-- diverging. A foreign key cannot express it and a CHECK cannot read another
-- table, so it is a trigger - which Prisma ignores, exactly like the
-- roll-horizon trigger in add_bas_tables.
--
-- org_id was NOT dropped from bas_sites instead, which would have removed the
-- redundancy outright: it is in the column list scripts/bas-tables.ts moves
-- from the standalone database, and that list is shared with the verifier.
--
-- Both directions are covered. Guarding only the bas_sites side would leave the
-- invariant half-true, which is worse than one you know you do not have: the
-- failure would surface as a building belonging to two different orgs depending
-- on which table you asked.
-- =============================================================================

CREATE FUNCTION bas_sites_project_org_match() RETURNS trigger
LANGUAGE plpgsql AS $fn$
DECLARE
  project_org bigint;
BEGIN
  -- A BEFORE ROW trigger runs before the column constraints AND before the
  -- foreign keys, so this function gets first refusal on rows whose real
  -- problem is neither of the things it exists to check. In both of those
  -- cases it must stand aside: PostgreSQL's own message names the actual
  -- fault, and anything raised here would replace it with a worse one.
  --
  -- This is not hypothetical. The first version checked org equality
  -- unconditionally, so an INSERT that simply omitted project_id - which is
  -- what the phb-bas collector's ensure_site() did - was refused with
  --
  --     bas_sites.org_id 5 does not match the org of project <NULL>
  --
  -- sending the reader to look for an org mismatch that did not exist. The
  -- missing column was the whole story.

  -- No project named: the NOT NULL constraint says so, precisely.
  IF NEW.project_id IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT org_id INTO project_org FROM bas_projects WHERE project_id = NEW.project_id;

  -- No such project: bas_sites_project_id_fkey says so, precisely.
  IF NOT FOUND THEN
    RETURN NEW;
  END IF;

  -- Both rows exist and disagree. That is this trigger's actual job, and
  -- nothing else in the database would catch it.
  IF project_org <> NEW.org_id THEN
    RAISE EXCEPTION
      'bas_sites.org_id % does not match the org of project % (which is %)',
      NEW.org_id, NEW.project_id, project_org;
  END IF;

  RETURN NEW;
END;
$fn$;

COMMENT ON FUNCTION bas_sites_project_org_match() IS
  'Keeps bas_sites.org_id equal to the org of its project. bas_sites.org_id is redundant '
  'with bas_projects.org_id and is kept only because scripts/bas-tables.ts moves it; this '
  'is what stops the two disagreeing. Prisma does not model triggers and will not drop it.';

CREATE TRIGGER bas_sites_project_org_match
  BEFORE INSERT OR UPDATE OF org_id, project_id ON bas_sites
  FOR EACH ROW EXECUTE FUNCTION bas_sites_project_org_match();

CREATE FUNCTION bas_projects_org_match() RETURNS trigger
LANGUAGE plpgsql AS $fn$
DECLARE
  stranded bigint;
BEGIN
  SELECT site_id INTO stranded
    FROM bas_sites
   WHERE project_id = NEW.project_id
     AND org_id IS DISTINCT FROM NEW.org_id
   LIMIT 1;

  IF stranded IS NOT NULL THEN
    RAISE EXCEPTION
      'cannot move project % to org %: building % under it belongs to a different org',
      NEW.project_id, NEW.org_id, stranded;
  END IF;

  RETURN NEW;
END;
$fn$;

COMMENT ON FUNCTION bas_projects_org_match() IS
  'The other half of bas_sites_project_org_match: stops a project being moved to a '
  'different org while buildings still under it name the old one.';

CREATE TRIGGER bas_projects_org_match
  BEFORE UPDATE OF org_id ON bas_projects
  FOR EACH ROW EXECUTE FUNCTION bas_projects_org_match();


-- =============================================================================
-- SECTION 5 - bas_v_data_dictionary excludes bas_station_credentials
--
-- READ THIS BEFORE TOUCHING THE PREDICATE. It already carries one warning in
-- add_bas_tables about the two silent ways to get the schema filter wrong. This
-- is a third.
--
-- The view selects every object matching `bas\_%` and exists to be pasted into
-- an LLM prompt. bas_station_credentials matches that pattern. Left alone, the
-- structure of the credentials table - its existence, its column names, and the
-- fact that a password lives in it - goes into the prompt of the AI whose SQL
-- tool is explicitly supposed to be denied that table.
--
-- It leaks no password. It does not need to: telling a model there is a
-- password_ciphertext column is the first half of asking for it, and the whole
-- reason the credentials are a separate table rather than columns on
-- bas_stations is so that this layer can say no.
--
-- bas_projects IS included, deliberately. It is ordinary hierarchy metadata and
-- the AI cannot answer "compare the two buildings on that property" without it.
--
-- CREATE OR REPLACE rather than DROP and recreate: the column list is
-- unchanged, and nothing depends on this view.
-- =============================================================================

CREATE OR REPLACE VIEW bas_v_data_dictionary AS
SELECT
    c.relname AS object_name,
    CASE c.relkind WHEN 'r' THEN 'table' WHEN 'v' THEN 'view' ELSE c.relkind::text END AS object_type,
    a.attname                            AS column_name,
    format_type(a.atttypid, a.atttypmod) AS data_type,
    NOT a.attnotnull                     AS is_nullable,
    col_description(c.oid, a.attnum)     AS column_description,
    obj_description(c.oid, 'pg_class')   AS object_description
FROM pg_class c
JOIN pg_namespace n ON n.oid = c.relnamespace
JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped
WHERE n.nspname = 'public'
  AND c.relname LIKE 'bas\_%'
  AND c.relname <> 'bas_station_credentials'
  AND c.relkind IN ('r','v')
ORDER BY c.relkind DESC, c.relname, a.attnum;

COMMENT ON VIEW bas_v_data_dictionary IS
  'The entire annotated BAS schema in one query. Intended to be selected and pasted into an '
  'LLM prompt as context, so the model writes SQL against documented columns rather than '
  'guessing from names. Scoped to bas_-prefixed objects: the platform''s own employee and '
  'audit tables are deliberately NOT exposed here, and bas_station_credentials is excluded '
  'by name - it is the one bas_ object the model is not told about. Keep the COMMENT ON '
  'statements current - they are not decoration, they are the model''s only description of '
  'what the data means.';


