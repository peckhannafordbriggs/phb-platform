-- =============================================================================
-- Everything above this line was generated by the Prisma migration engine.
-- Everything below it was written by hand, because Prisma cannot express it.
--
-- ONE line above was edited, and only one. Prisma emits
--
--     ALTER TABLE "bas_sites" ADD COLUMN "project_id" BIGINT NOT NULL;
--
-- which is correct for an empty database and fails on every database that has
-- a building in it. It is added nullable here and set NOT NULL in Section 3,
-- after the backfill has filled it. The END STATE is identical to what Prisma
-- asked for - a NOT NULL bigint with that foreign key - and the end state is
-- what the shadow-database diff compares. `migrate dev --create-only` still
-- reports an empty migration afterwards, and that is the check that this was
-- safe rather than merely plausible.
--
-- The same rule as add_bas_tables applies to the rest: Prisma models columns,
-- indexes and foreign keys. It does not model CHECK constraints, triggers or
-- views, so those are invisible to it in both directions and live here.
--
--   Section 1  The connection_mode CHECK constraint.
--   Section 2  The backfill. One project, one building, one station - the ones
--              that actually exist.
--   Section 3  bas_sites.project_id becomes NOT NULL.
--   Section 4  Two triggers keeping bas_sites.org_id and bas_projects.org_id
--              from disagreeing.
--   Section 5  bas_v_data_dictionary, replaced to EXCLUDE the credentials
--              table. Read that section before touching the predicate.
--   Section 6  COMMENT ON for the new objects.
--   Section 7  A defensive REVOKE on the credentials table.
-- =============================================================================


-- =============================================================================
-- SECTION 1 - CHECK constraint
--
-- The fourteenth in this schema. CHECK-over-text rather than a Postgres enum,
-- for the same reason as the thirteen in add_bas_tables: an enum column changes
-- how the collector's inserts bind their parameters, and decision D1 says the
-- collector changes only its connection string.
--
-- Deliberately the ONLY constraint on this column. Two coherence rules are NOT
-- enforced here:
--
--   * 'direct' does not require base_url
--   * 'via_parent' does not require parent_station_id
--
-- Both are tempting and both are wrong at this layer. A station discovered
-- behind a central collector and not yet configured has neither, and the
-- Settings tab has to be able to list it as "discovered, unassigned"
-- (docs/B7_settings_and_hierarchy_plan.md, Risks). A constraint that refused to
-- store that row would make the incomplete state unrepresentable instead of
-- visible. Those two rules belong in the B7.4 form validation.
-- =============================================================================

ALTER TABLE bas_stations
  ADD CONSTRAINT bas_stations_connection_mode_check
  CHECK (connection_mode IN ('direct','via_parent'));


-- =============================================================================
-- SECTION 2 - Backfill
--
-- Exactly one project, one building and one station, all of them things that
-- exist. No example rows, no "Liberty Center", no placeholder org.
--
-- This project has a standing rule against plausible-looking invented data:
-- Temp1-Temp3 are left unclassified because nobody knows what they represent,
-- and giving them a made-up role would make the AI answer confidently about
-- something untrue. A fake project row is the same mistake with a longer fuse -
-- it reaches a dropdown, and somebody believes it.
--
-- On a fresh database all of this is a no-op. That is the normal case for the
-- test database and for a first deployment, and it is why the block returns
-- early rather than inserting a project with no buildings under it.
-- =============================================================================

DO $backfill$
DECLARE
  orphan_orgs   bigint[];
  target_org    bigint;
  new_project   bigint;
  moved         integer;
BEGIN
  SELECT array_agg(DISTINCT org_id) INTO orphan_orgs
    FROM bas_sites WHERE project_id IS NULL;

  -- Fresh database: no buildings, so nothing to place and no project to invent.
  IF orphan_orgs IS NULL THEN
    RAISE NOTICE 'B7.1 backfill: no buildings to place, no project created.';
    RETURN;
  END IF;

  -- There is one org. If that is ever untrue, the right answer is a human
  -- naming each project, not this migration copying one name across all of
  -- them - which is precisely the invented-data failure described above.
  IF array_length(orphan_orgs, 1) > 1 THEN
    RAISE EXCEPTION
      'B7.1 backfill expected buildings under exactly one org, found % (org_ids %). '
      'Create the projects by hand and re-run - do not let this migration name them.',
      array_length(orphan_orgs, 1), orphan_orgs;
  END IF;

  target_org := orphan_orgs[1];

  INSERT INTO bas_projects (org_id, name, notes)
  VALUES (
    target_org,
    'Peck Hannaford + Briggs',
    'Created by the B7.1 backfill so the one existing building had a project to sit under. '
    'Not a placeholder - it is the real project name.'
  )
  RETURNING project_id INTO new_project;

  UPDATE bas_sites SET project_id = new_project WHERE project_id IS NULL;
  GET DIAGNOSTICS moved = ROW_COUNT;

  RAISE NOTICE 'B7.1 backfill: project % created under org %, % building(s) placed.',
    new_project, target_org, moved;
END
$backfill$;

-- Every station already carries a connection_mode - the column is NOT NULL with
-- a 'via_parent' default, so the ALTER above filled it. This corrects the ones
-- we actually reach ourselves.
--
-- Derived from what the rows say rather than from a station name typed in here.
-- A station with an oBIX base_url and no parent is, by definition, one that
-- nothing else is importing for us. Today that matches exactly one row,
-- SpringGroveLabComputer - whose name is NOT touched by this statement or any
-- other in this migration. It is case-sensitive and appears literally in every
-- oBIX URL.
--
-- base_url is not rewritten either. The stored value has no trailing slash and
-- the collector in phb-bas builds its URLs from it as it stands; "correcting"
-- that here would change a live string for cosmetics.
UPDATE bas_stations
   SET connection_mode = 'direct'
 WHERE base_url IS NOT NULL
   AND parent_station_id IS NULL;


