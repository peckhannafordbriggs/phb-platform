-- =============================================================================
-- SECTION 7 - a defensive REVOKE on the credentials table
--
-- Belt and braces, and NOT the real fix. The real fix is in the other repo.
--
-- setup_readonly_role_platform.sql (in bas-mcp, run by hand after any migration
-- that adds a bas_ object - see runbook.md) grants SELECT table by table across
-- everything matching `bas\_%`. bas_station_credentials matches. So the next
-- time anybody runs that script, bas_readonly_platform is handed read access to
-- the ciphertext table, and nothing in this repo can prevent it.
--
-- That script needs an explicit exclusion. Until it has one, this at least
-- means the table does not start out readable.
--
-- Guarded on the role existing: it is created by hand on the machines that have
-- Grafana, and a fresh database or CI has no such role. An unguarded REVOKE
-- would fail the migration there under ON_ERROR_STOP=1.
--
-- bas_collector is deliberately NOT revoked. Under D15 the collector reads its
-- own targets and credentials from this table.
-- =============================================================================

DO $revoke$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'bas_readonly_platform') THEN
    EXECUTE 'REVOKE ALL ON TABLE bas_station_credentials FROM bas_readonly_platform';
    RAISE NOTICE 'Revoked bas_readonly_platform on bas_station_credentials.';
  END IF;
END
$revoke$;
